// Read-only key list, so data mappers (utils/issueVisuals.js) can check a
// server icon string against the one icon source without importing glyphs.
export const GLYPH_NAMES = Object.freeze(Object.keys(GLYPHS));

export function hasGlyph(name) {
  return typeof name === "string" && Object.hasOwn(GLYPHS, name);
}

export function Icon({ name, cls = "", label, ...rest }) {
  const Glyph = Object.hasOwn(GLYPHS, name) ? GLYPHS[name] : null;
  if (!Glyph) {
    if (import.meta.env.DEV) console.warn(`Icon: unknown glyph name "${name}"`);
    return null;
  }
  const className = cls ? `ico ${cls}` : "ico";
  if (label) {
    return <Glyph className={className} role="img" aria-label={label} focusable="false" {...rest} />;
  }
  return <Glyph className={className} aria-hidden="true" focusable="false" {...rest} />;
}

